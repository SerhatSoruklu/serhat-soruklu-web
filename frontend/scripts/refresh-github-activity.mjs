import { execFileSync } from 'node:child_process';
import { writeFile } from 'node:fs/promises';

// Read-only GitHub GraphQL access through the developer's existing gh session.
// Persist aggregate counts only: never tokens, repository names or commit messages.
const login = 'SerhatSoruklu';
const now = new Date();
const years = [];
for (let year = 2023; year <= now.getUTCFullYear(); year += 1) {
  const from = `${year}-01-01T00:00:00Z`;
  const to = year === now.getUTCFullYear() ? now.toISOString() : `${year}-12-31T23:59:59Z`;
  const query = `query { user(login: "${login}") { contributionsCollection(from: "${from}", to: "${to}") { totalCommitContributions restrictedContributionsCount contributionCalendar { totalContributions weeks { contributionDays { date contributionCount contributionLevel } } } } } }`;
  const response = JSON.parse(execFileSync('gh', ['api', 'graphql', '-f', `query=${query}`], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] }));
  if (response.errors || !response.data?.user) throw new Error('GitHub did not return a complete contribution calendar.');
  const collection = response.data.user.contributionsCollection;
  const levels = ['NONE', 'FIRST_QUARTILE', 'SECOND_QUARTILE', 'THIRD_QUARTILE', 'FOURTH_QUARTILE'];
  const days = collection.contributionCalendar.weeks.flatMap(week => week.contributionDays)
    .filter(day => day.date.startsWith(String(year)))
    .map(day => {
      const level = levels.indexOf(day.contributionLevel);
      if (!/^\d{4}-\d{2}-\d{2}$/.test(day.date) || !Number.isSafeInteger(day.contributionCount) || day.contributionCount < 0 || level < 0) throw new Error('Invalid contribution day.');
      return [day.date, day.contributionCount, level];
    });
  const total = days.reduce((sum, day) => sum + day[1], 0);
  if (total !== collection.contributionCalendar.totalContributions) throw new Error(`Calendar total mismatch for ${year}.`);
  years.push({ year, total, commitContributions: collection.totalCommitContributions, privateContributions: collection.restrictedContributionsCount, days });
}
const snapshot = { login, fetchedAt: now.toISOString(), source: `https://github.com/${login}`, years };
const output = new URL('../src/app/pages/github/github-activity.data.ts', import.meta.url);
await writeFile(output, `// Generated by npm run refresh:github-activity. Aggregate GitHub data; no repository details.\nexport const githubActivitySnapshot = ${JSON.stringify(snapshot)};\n`);
console.log(`Updated ${years.length} verified calendars, ${years.reduce((sum, year) => sum + year.total, 0)} contributions. Snapshot: ${snapshot.fetchedAt}`);
